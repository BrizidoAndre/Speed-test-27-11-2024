<?php

namespace app\controllers;

use Yii;
use yii\filters\AccessControl;
use yii\web\Controller;
use yii\web\Response;
use yii\filters\VerbFilter;
use app\models\LoginForm;
use app\models\ContactForm;
use yii\web\ResponseFormatterInterface;

class SiteController extends Controller
{
    /**
     * {@inheritdoc}
     */
    public function behaviors()
    {
        return [
            'access' => [
                'class' => AccessControl::class,
                'only' => ['logout'],
                'rules' => [
                    [
                        'actions' => ['logout'],
                        'allow' => true,
                        'roles' => ['@'],
                    ],
                ],
            ],
            'verbs' => [
                'class' => VerbFilter::class,
                'actions' => [
                    'logout' => ['post'],
                ],
            ],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function actions()
    {
        return [
            'error' => [
                'class' => 'yii\web\ErrorAction',
            ],
            'captcha' => [
                'class' => 'yii\captcha\CaptchaAction',
                'fixedVerifyCode' => YII_ENV_TEST ? 'testme' : null,
            ],
        ];
    }

    /**
     * Displays homepage.
     *
     * @return string
     */
    public function actionIndex()
    {
        $month = Yii::$app->request->getBodyParam('month', date('m'));
        $year = Yii::$app->request->getBodyParam('year', date('Y'));

        $firstDayOfMonth = (new \DateTime())->setDate($year, $month, 1);
        $lastDayOfMonth = (new \DateTime())->setDate($year, $month + 1, 0);

        $days = [];
        for ($i = 0; $i < (int)$firstDayOfMonth->format('N'); $i++) {
            $days[] = (new \DateTime())->setDate($year, $month, -$i);
        }

        for ($i = 1; $i <= (int) $lastDayOfMonth->format('d'); $i++) {
            $days[] = (new \DateTime())->setDate($year, $month, $i);
        }

        for ($j = (int) $lastDayOfMonth->format('d'); $j < 7; $j++) {
            $days[] = (new \DateTime())->setDate($year, $month + 1, $i);
        }

        return $this->render('index', [
            'days' => $days
        ]);
    }

    public function debug($array)
    {
        echo '<pre>' . print_r($array, true) . '</pre>';
    }

    /**
     * Login action.
     *
     * @return Response|string
     */
    public function actionLogin()
    {
        if (!Yii::$app->user->isGuest) {
            return $this->goHome();
        }

        $model = new LoginForm();
        if ($model->load(Yii::$app->request->post()) && $model->login()) {
            return $this->goBack();
        }

        $model->password = '';
        return $this->render('login', [
            'model' => $model,
        ]);
    }

    /**
     * Logout action.
     *
     * @return Response
     */
    public function actionLogout()
    {
        Yii::$app->user->logout();

        return $this->goHome();
    }

    /**
     * Displays contact page.
     *
     * @return Response|string
     */
    public function actionContact()
    {
        $model = new ContactForm();
        if ($model->load(Yii::$app->request->post()) && $model->contact(Yii::$app->params['adminEmail'])) {
            Yii::$app->session->setFlash('contactFormSubmitted');

            return $this->refresh();
        }
        return $this->render('contact', [
            'model' => $model,
        ]);
    }

    /**
     * Displays about page.
     *
     * @return string
     */
    public function actionAbout()
    {
        return $this->render('about');
    }
}
